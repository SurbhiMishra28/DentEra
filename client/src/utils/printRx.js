// printRx.js — print a prescription (the clinic's Rx slip). Same print-window pattern
// as receipt.js: inline styles, HTML-escaped, "Save as PDF" from the browser dialog.
const A = String.fromCharCode(38)
const esc = s => String(s == null ? '' : s)
  .replace(new RegExp(A, 'g'), A + 'amp;').replace(/</g, A + 'lt;').replace(/>/g, A + 'gt;').replace(/"/g, A + 'quot;')

// frequency short forms kept on one line each: "1-0-1" style dosing under each medicine
export function printRx({ clinic = 'DentEra Dental Clinic', prescription, patient, items = [], dentist }) {
  const rx = prescription || {}
  const lines = items.length
    ? items.map((it, i) => `<tr>
        <td>${i + 1}</td>
        <td><b>${esc(it.medicine)}</b>${it.dose ? `<br/><small>${esc(it.dose)}</small>` : ''}</td>
        <td>${esc(it.frequency || '—')}</td>
        <td class="r">${it.days ? esc(it.days) + ' days' : '—'}</td>
      </tr>`).join('')
    : `<tr><td colspan="4" class="muted">No medicines recorded.</td></tr>`
  const when = (rx.created_at || '').replace('T', ' ').slice(0, 16)
  const w = window.open('', '_blank', 'width=760,height=900')
  if (!w) { alert('Please allow pop-ups for this site to print the prescription.'); return }
  w.document.write(`<!doctype html><html><head><meta charset="utf-8"><title>Prescription #${esc(rx.id)} — ${esc(clinic)}</title>
  <style>
    *{box-sizing:border-box}
    body{font-family:'Segoe UI',system-ui,sans-serif;color:#16302b;margin:0;padding:38px 44px}
    .head{display:flex;justify-content:space-between;align-items:flex-start;border-bottom:3px solid #0fa795;padding-bottom:16px}
    .brand{font-size:26px;font-weight:800;letter-spacing:-.02em;color:#0b7c72}
    .brand small{display:block;font-size:11px;font-weight:600;color:#5b7a74;letter-spacing:.14em;text-transform:uppercase;margin-top:3px}
    .meta{text-align:right;font-size:12.5px;color:#41626c;line-height:1.7}
    .meta b{color:#16302b}
    h2{margin:22px 0 4px;font-size:17px}
    .who{font-size:13.5px;color:#41626c;line-height:1.8;margin:0 0 6px}
    table{width:100%;border-collapse:collapse;margin-top:10px;font-size:13.5px}
    th{text-align:left;font-size:11px;text-transform:uppercase;letter-spacing:.06em;color:#5b7a74;border-bottom:2px solid #dfecef;padding:8px 6px}
    td{padding:9px 6px;border-bottom:1px solid #eef3f2;vertical-align:top}
    td.r,th.r{text-align:right}
    small{color:#7d9793}
    .block{margin-top:16px;border:1px solid #dfecef;border-radius:12px;padding:12px 14px;font-size:13.5px;line-height:1.7}
    .block span{display:block;font-size:11px;text-transform:uppercase;letter-spacing:.08em;color:#5b7a74;margin-bottom:4px}
    .sign{margin-top:44px;display:flex;justify-content:space-between;align-items:flex-end;font-size:12.5px;color:#41626c}
    .sign .line{border-top:1px solid #9fc0bb;width:230px;padding-top:6px;text-align:center}
    .foot{margin-top:26px;border-top:1px solid #dfecef;padding-top:12px;font-size:11.5px;color:#7d9793;line-height:1.7}
    @media print{body{padding:18px 22px}}
  </style></head><body>
    <div class="head">
      <div class="brand">${esc(clinic)}<small>Prescription</small></div>
      <div class="meta"><b>Rx #${esc(rx.id)}</b><br/>Date: ${esc(when || '—')}<br/>${dentist ? `Dr. <b>${esc(dentist.name || '—')}</b>` : ''}</div>
    </div>
    <h2>Patient</h2>
    <p class="who">
      <b>${esc(patient ? patient.name : 'Patient')}</b>${patient && patient.dob ? ` · b. ${esc(patient.dob)}` : ''}${patient && patient.phone ? ` · ${esc(patient.phone)}` : ''}<br/>
      ${dentist && dentist.specialty ? esc(dentist.specialty) : ''}
    </p>
    ${rx.diagnosis ? `<div class="block"><span>Diagnosis</span>${esc(rx.diagnosis)}</div>` : ''}
    <table><thead><tr><th style="width:44px">#</th><th>Medicine</th><th>Dosage / frequency</th><th class="r" style="width:90px">Duration</th></tr></thead>
      <tbody>${lines}</tbody></table>
    ${rx.advice ? `<div class="block"><span>Advice</span>${esc(rx.advice)}</div>` : ''}
    <div class="sign"><span>Patient signature</span><span class="line">${esc(dentist && dentist.name ? 'Dr. ' + dentist.name : 'Dentist')}</span></div>
    <div class="foot">Take medicines exactly as directed. If a rash, swelling or breathing trouble appears, stop and contact the clinic immediately.<br/>
      Generated by DentEra on ${esc(new Date().toLocaleString('en-IN'))}.</div>
  </body></html>`)
  w.document.close()
  w.focus()
  setTimeout(() => { try { w.print() } catch { /* user can print manually */ } }, 350)
}
