// receipt.js — print an invoice as a clinic receipt (browser print dialog can "Save as PDF").
// Opens a small print window with inline styles; no print library, no extra dependency.
// HTML-escape for the print window (entities built via char codes so nothing decodes in transit)
const A = String.fromCharCode(38) // the ampersand
const esc = s => {
  const t = String(s == null ? '' : s)
  return t.replace(new RegExp(A, 'g'), A + 'amp;')
    .replace(/</g, A + 'lt;').replace(/>/g, A + 'gt;').replace(/"/g, A + 'quot;')
}
const money = n => '₹' + Number(n || 0).toLocaleString('en-IN')

export function printReceipt({ clinic = 'DentEra Dental Clinic', invoice, patient, plan, items = [], dentist, due }) {
  const inv = invoice || {}
  const stampBg = inv.status === 'paid' ? '#dcf5ea' : inv.status === 'partial' ? '#fff4dd' : '#fdecec'
  const stampFg = inv.status === 'paid' ? '#00695c' : inv.status === 'partial' ? '#9a6b00' : '#b3261e'
  const rows = items.length
    ? items.map(it => `<tr>
        <td>${esc(it.visit_no || '—')}</td>
        <td>${esc(it.treatment_name || 'Treatment')}${it.tooth_fdi ? ` <small>(tooth ${esc(it.tooth_fdi)})</small>` : ''}</td>
        <td>${esc(it.status || '—')}</td>
        <td class="r">${money(it.cost)}</td>
      </tr>`).join('')
    : `<tr><td>1</td><td>${esc(plan ? plan.title || 'Treatment plan' : 'Treatment / procedure')}</td><td>—</td><td class="r">${money(inv.amount)}</td></tr>`
  const when = (inv.issued_at || '').replace('T', ' ').slice(0, 16)
  const w = window.open('', '_blank', 'width=760,height=900')
  if (!w) { alert('Please allow pop-ups for this site to print the receipt.'); return }
  w.document.write(`<!doctype html><html><head><meta charset="utf-8"><title>Invoice #${esc(inv.id)} — ${esc(clinic)}</title>
  <style>
    *{box-sizing:border-box}
    body{font-family:'Segoe UI',system-ui,sans-serif;color:#16302b;margin:0;padding:38px 44px}
    .head{display:flex;justify-content:space-between;align-items:flex-start;border-bottom:3px solid #0fa795;padding-bottom:16px}
    .brand{font-size:26px;font-weight:800;letter-spacing:-.02em;color:#0b7c72}
    .brand small{display:block;font-size:11px;font-weight:600;color:#5b7a74;letter-spacing:.14em;text-transform:uppercase;margin-top:3px}
    .meta{text-align:right;font-size:12.5px;color:#41626c;line-height:1.7}
    .meta b{color:#16302b}
    h2{margin:22px 0 4px;font-size:17px}
    .who{font-size:13.5px;color:#41626c;line-height:1.8;margin:0 0 6px}
    table{width:100%;border-collapse:collapse;margin-top:10px;font-size:13.5px}
    th{text-align:left;font-size:11px;text-transform:uppercase;letter-spacing:.06em;color:#5b7a74;border-bottom:2px solid #dfecef;padding:8px 6px}
    td{padding:9px 6px;border-bottom:1px solid #eef3f2;vertical-align:top}
    td.r,th.r{text-align:right}
    small{color:#7d9793}
    .totals{margin-top:14px;margin-left:auto;width:290px;font-size:13.5px}
    .totals div{display:flex;justify-content:space-between;padding:5px 2px}
    .totals .due{border-top:2px solid #0fa795;margin-top:6px;padding-top:9px;font-weight:800;font-size:15px;color:#0b7c72}
    .stamp{display:inline-block;margin-top:14px;padding:5px 14px;border-radius:999px;font-size:11.5px;font-weight:800;letter-spacing:.08em;text-transform:uppercase;
      background:${stampBg};color:${stampFg}}
    .foot{margin-top:34px;border-top:1px solid #dfecef;padding-top:12px;font-size:11.5px;color:#7d9793;line-height:1.7}
    @media print{body{padding:18px 22px}}
  </style></head><body>
    <div class="head">
      <div class="brand">${esc(clinic)}<small>Dental care, in one place</small></div>
      <div class="meta"><b>Invoice #${esc(inv.id)}</b><br/>Issued: ${esc(when || '—')}<br/>Status: <b>${esc(inv.status || '—')}</b></div>
    </div>
    <h2>Billed to</h2>
    <p class="who">
      <b>${esc(patient ? patient.name : 'Walk-in patient')}</b>${patient && patient.phone ? ` · ${esc(patient.phone)}` : ''}<br/>
      ${dentist ? `Dentist: <b>${esc(dentist)}</b><br/>` : ''}${plan && plan.title ? `Plan: ${esc(plan.title)}<br/>` : ''}
    </p>
    <table><thead><tr><th style="width:52px">Visit</th><th>Treatment</th><th style="width:90px">Status</th><th class="r" style="width:110px">Cost</th></tr></thead>
    <tbody>${rows}</tbody></table>
    <div class="totals">
      <div><span>Subtotal</span><b>${money(inv.amount)}</b></div>
      ${inv.discount ? `<div><span>Discount</span><b>− ${money(inv.discount)}</b></div>` : ''}
      <div><span>Paid</span><b>${money(inv.paid_amount)}</b></div>
      <div class="due"><span>Balance due</span><span>${money(due)}</span></div>
    </div>
    <span class="stamp">${esc(inv.status || '')}</span>
    <div class="foot">Thank you for choosing ${esc(clinic)}. This is a system-generated receipt — no signature required.<br/>
      Generated by DentEra on ${esc(new Date().toLocaleString('en-IN'))}.</div>
  </body></html>`)
  w.document.close()
  w.focus()
  setTimeout(() => { try { w.print() } catch { /* user can print manually */ } }, 350)
}
